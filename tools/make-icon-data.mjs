// Writes main-site/js/icon-data.js: the brand logos (Simple Icons, CC0-1.0)
// and the general icons (Feather, MIT) that links can use.
//
// Usage, from tools/:  npm install && npm run icons
//
// Add a brand or a general icon by adding its name below and running this
// again; then add it to LINK_ICONS in main-site/api/_lib/validate.js (the
// tests check the two lists agree) and bump the service worker version.

import { writeFileSync, readFileSync } from 'node:fs';
import * as simpleIcons from 'simple-icons';
import feather from 'feather-icons';

// Simple Icons slugs. The key is the icon name stored on a link.
const BRANDS = [
  'instagram', 'x', 'threads', 'bluesky', 'facebook', 'tiktok', 'mastodon', 'tumblr', 'reddit',
  'snapchat', 'pinterest', 'xiaohongshu', 'youtube', 'twitch', 'kick', 'vimeo', 'bilibili',
  'spotify', 'soundcloud', 'bandcamp', 'applemusic', 'youtubemusic', 'applepodcasts',
  'telegram', 'discord', 'whatsapp', 'line', 'furaffinity', 'deviantart', 'artstation', 'pixiv',
  'behance', 'dribbble', 'vrchat', 'patreon', 'kofi', 'buymeacoffee', 'gumroad', 'substack',
  'medium', 'etsy', 'redbubble', 'threadless', 'shopee', 'paypal', 'cashapp', 'venmo', 'steam',
  'itchdotio', 'github', 'gitlab', 'linktree',
];

// Feather icons, by Feather name, stored under the name on the right. The
// original twenty link icons keep their own drawings in icons.js.
const FEATHER = {
  home: 'home', user: 'user', users: 'users', info: 'info', bookmark: 'bookmark', award: 'award',
  zap: 'zap', film: 'film', headphones: 'headphones', image: 'image', radio: 'radio', tv: 'tv',
  at: 'at-sign', send: 'send', cart: 'shopping-cart', card: 'credit-card', dollar: 'dollar-sign',
  coffee: 'coffee', tag: 'tag', brush: 'pen-tool', pencil: 'edit-3', feather: 'feather', book: 'book',
  'book-open': 'book-open', terminal: 'terminal', cpu: 'cpu', compass: 'compass', clock: 'clock',
  briefcase: 'briefcase', sun: 'sun', moon: 'moon', cloud: 'cloud', smile: 'smile', box: 'box',
  layers: 'layers', package: 'package', rss: 'rss', download: 'download', 'map-pin': 'map-pin',
  monitor: 'monitor', smartphone: 'smartphone',
};

const brandData = {};
for (const slug of BRANDS) {
  const key = `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`;
  const icon = simpleIcons[key];
  if (!icon) throw new Error(`Simple Icons has no ${slug}`);
  brandData[slug] = { title: icon.title, path: icon.path };
}

const featherData = {};
for (const [name, source] of Object.entries(FEATHER)) {
  const icon = feather.icons[source];
  if (!icon) throw new Error(`Feather has no ${source}`);
  featherData[name] = icon.contents;
}

const versionOf = (pkg) => JSON.parse(readFileSync(new URL(`./node_modules/${pkg}/package.json`, import.meta.url), 'utf8')).version;

const out = `// Generated by tools/make-icon-data.mjs. Do not edit by hand.
//
// BRANDS: logos from Simple Icons ${versionOf('simple-icons')} (CC0-1.0,
// https://simpleicons.org). Brand names and logos belong to their owners and
// are shown only to mark a link to that service.
// FEATHER: general icons from Feather ${versionOf('feather-icons')} (MIT, https://feathericons.com).

export const BRANDS = ${JSON.stringify(brandData, null, 2)};

export const FEATHER = ${JSON.stringify(featherData, null, 2)};
`;
writeFileSync(new URL('../main-site/js/icon-data.js', import.meta.url), out);
console.log(`wrote ${Object.keys(brandData).length} brands and ${Object.keys(featherData).length} general icons`);
