// ESLint 9 flat config: `npm run lint`.
//
// It enforces Augy's code style decisions for help desk #17 (decisions 6 and
// 8): no ternaries, braces on every if / else / for / while, names of at
// least two letters, and no `&&`, `||`, `??` or `?.` used to produce a value.
// `&&` and `||` inside an `if` condition are fine; they are conditions, not
// values. Arrow functions stay.
//
// Files are split by where they run, so each gets the right globals:
//   - js/       browser modules (js/analytics.js is a classic script, and
//               js/bg-removal-worker.js runs in a Web Worker)
//   - sw.js     the service worker, a classic script
//   - api/, scripts/ and this file   Node ES modules
//
// Not linted (decision 5: only OneLink's own code is rewritten): the shared
// GFTV spec copies, the translations in assets/i18n/, the vendored libraries
// (js/vendor/ and onnxruntime in assets/vendor/), the generated icon file,
// and the tests.

import js from '@eslint/js';
import globals from 'globals';

// Decision 6: `&&` and `||` may not produce a value. Each selector is one
// place a value goes; a LogicalExpression anywhere else (an `if`, `while` or
// `for` condition, or inside a larger condition) is still allowed.
// `[operator!='??']` leaves `??` to its own rule below, so it is reported
// once.
const valueMessage =
  'Decision 6: `&&` / `||` used as a value is shorthand. Write an `if` / `else` block that sets the value.';
const logicalAsValue = [
  "VariableDeclarator > LogicalExpression[operator!='??'].init",
  "AssignmentExpression > LogicalExpression[operator!='??'].right",
  "ReturnStatement > LogicalExpression[operator!='??'].argument",
  "Property > LogicalExpression[operator!='??'].value",
  "ArrowFunctionExpression > LogicalExpression[operator!='??'].body",
  "CallExpression > LogicalExpression[operator!='??'].arguments",
].map((selector) => ({ selector, message: valueMessage }));

const styleRules = {
  // Decision 6: no ternaries `a ? b : c`. Use `if` / `else`.
  'no-ternary': 'error',

  // Decision 6: braces on every `if`, `else`, `for` and `while`.
  curly: ['error', 'all'],

  // Decision 7: no one-letter names. `id` and `to` are named as exceptions
  // in job 10. Property names are not checked: field names from the API, the
  // database and outside services (SimpleWebAuthn's options, Telegram's
  // fields, Supabase client calls) must not be renamed.
  'id-length': ['error', { min: 2, exceptions: ['id', 'to'], properties: 'never' }],

  // Decision 6: the other shorthand forms.
  'no-restricted-syntax': [
    'error',
    {
      selector: 'ChainExpression',
      message: 'Decision 6: optional chaining `?.` is shorthand. Check for null / undefined in an `if` block.',
    },
    {
      selector: "LogicalExpression[operator='??']",
      message: 'Decision 6: `??` is shorthand. Check for null / undefined in an `if` block.',
    },
    {
      selector: "AssignmentExpression[operator='??='], AssignmentExpression[operator='||='], AssignmentExpression[operator='&&=']",
      message: 'Decision 6: `??=`, `||=` and `&&=` are shorthand. Write an `if` block that assigns.',
    },
    ...logicalAsValue,
  ],
};

export default [
  {
    // Decision 5: not OneLink's own code, so not rewritten or linted.
    // js/icon-data.js is generated by tools/make-icon-data.mjs. node_modules/
    // is ignored by ESLint already; migrations/ sits outside this folder
    // (../migrations) and holds only SQL.
    ignores: [
      'js/theme.js',
      'js/prepaint.js',
      'js/official-bar.js',
      'js/update-bar.js',
      'js/icon-data.js',
      'js/vendor/',
      'assets/vendor/',
      'assets/i18n/',
      'tests/',
      'migrations/',
      'node_modules/',
    ],
  },

  // ESLint's recommended checks (undefined names, unreachable code and the
  // like), for every linted file.
  js.configs.recommended,

  // The code style rules, for every linted file.
  {
    rules: styleRules,
  },

  // Browser modules. The worker gets its own globals below.
  {
    files: ['js/**/*.js'],
    ignores: ['js/bg-removal-worker.js'],
    languageOptions: {
      sourceType: 'module',
      globals: { ...globals.browser },
    },
  },

  // Loaded with a plain <script> tag on the public pages.
  {
    files: ['js/analytics.js'],
    languageOptions: {
      sourceType: 'script',
    },
  },

  // Background removal, started as a module Web Worker by
  // js/avatar-composer.js.
  {
    files: ['js/bg-removal-worker.js'],
    languageOptions: {
      sourceType: 'module',
      globals: { ...globals.worker },
    },
  },

  // The service worker, registered as a classic script.
  {
    files: ['sw.js'],
    languageOptions: {
      sourceType: 'script',
      globals: { ...globals.serviceworker },
    },
  },

  // The API (Vercel Node functions), scripts and this config file: Node ES
  // modules ("type": "module" in package.json).
  {
    files: ['api/**/*.js', 'scripts/**/*.js', 'eslint.config.js'],
    languageOptions: {
      sourceType: 'module',
      globals: { ...globals.node },
    },
  },

  // The API refuses control characters in links and strips them, with the
  // invisible format characters (zero-width spaces, direction marks), out of
  // names, bios and titles (api/_lib/validate.js). A regular expression that
  // matches them is intended there, and the format characters are written
  // in it as the characters themselves.
  {
    files: ['api/**/*.js'],
    rules: {
      'no-control-regex': 'off',
      'no-irregular-whitespace': ['error', { skipRegExps: true }],
    },
  },
];
